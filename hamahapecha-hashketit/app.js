const fantasyEl = document.getElementById("fantasy-cards");

function renderFantasy() {
  fantasyEl.innerHTML = FANTASY.map((f, i) => `
    <article class="card card-fantasy" data-f="${i}" tabindex="0" role="button" aria-label="${f.name} - מקצוע דמיוני">
      <div class="card-head">
        <h3>${f.name}</h3>
        <span class="badge badge-fantasy">דמיון, לא תחזית</span>
      </div>
      <p class="why-short">${f.teaser}</p>
    </article>`).join("");
}

function openFantasyModal(i) {
  const f = FANTASY[i];
  lastFocused = document.activeElement;
  modalBody.innerHTML = `
    <h3>${f.name}</h3>
    <span class="badge badge-fantasy">דמיון, לא תחזית</span>
    <h4>הצורך שיוליד את המקצוע</h4>
    <p>${f.need}</p>
    <h4>איך נראה יום עבודה</h4>
    <p>${f.day}</p>
    <p class="fantasy-disclaimer">מקצוע דמיוני. אין כיום משרה כזו (למיטב ידיעתנו), ואין כאן תחזית מחקרית - בניגוד למפת המקצועות למעלה, הטור הזה נכתב כדי לפתוח את הראש.</p>`;
  modal.hidden = false;
  document.body.style.overflow = "hidden";
  modal.querySelector(".modal-close").focus();
}

fantasyEl.addEventListener("click", e => {
  const c = e.target.closest(".card-fantasy");
  if (c) openFantasyModal(+c.dataset.f);
});
fantasyEl.addEventListener("keydown", e => {
  if (e.key !== "Enter" && e.key !== " ") return;
  const c = e.target.closest(".card-fantasy");
  if (c) { e.preventDefault(); openFantasyModal(+c.dataset.f); }
});

renderFantasy();

render();

