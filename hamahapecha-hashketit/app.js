const cardsEl = document.getElementById("cards");
const searchEl = document.getElementById("search");
const chips = document.querySelectorAll(".chip");
const modal = document.getElementById("modal");
const modalBody = document.getElementById("modal-body");

let activeFilter = "all";
let query = "";

function badgeClass(t) { return t === "high" ? "badge-high" : t === "mid" ? "badge-mid" : "badge-low"; }

function render() {
  const q = query.trim();
  const list = JOBS.filter(j =>
    (activeFilter === "all" || j.tier === activeFilter) &&
    (!q || j.name.includes(q) || j.evidence.includes(q) || j.read.includes(q))
  );
  if (!list.length) {
    cardsEl.innerHTML = '<p class="empty">לא נמצאו מקצועות מתאימים. נסו חיפוש אחר.</p>';
    return;
  }
  cardsEl.innerHTML = list.map(j => `
    <article class="card tier-${j.tier}" data-i="${JOBS.indexOf(j)}" tabindex="0" role="button" aria-label="${j.name}">
      <div class="card-head">
        <h3>${j.name}</h3>
        <span class="badge ${badgeClass(j.tier)}">${TIERS[j.tier]}</span>
      </div>
      <p class="why-short">${j.evidence.split(".")[0]}.</p>
    </article>`).join("");
}

let lastFocused = null;
function openModal(i) {
  lastFocused = document.activeElement;
  const j = JOBS[i];
  const jobUrl = "https://www.jobmaster.co.il/jobs/?q=" + encodeURIComponent(j.q);
  modalBody.innerHTML = `
    <h3>${j.name}</h3>
    <span class="badge ${badgeClass(j.tier)}">${TIERS[j.tier]}</span>
    <h4>מה המחקר מצא</h4>
    <p>${j.evidence}</p>
    <h4>איך לקרוא את זה</h4>
    <p>${j.read}</p>
    <p class="src">מקורות: ${j.src.join(" · ")}</p>
    <p class="jobsearch"><a href="${jobUrl}" target="_blank" rel="noopener">חיפוש משרות ב${j.q} בג'ובמאסטר</a><br>
    <span>קישור חיפוש חיצוני. התוצאות משתנות ואינן מאומתות על ידינו - אין הבטחה שקיימות משרות פנויות כרגע.</span></p>`;
  modal.hidden = false;
  document.body.style.overflow = "hidden";
  modal.querySelector(".modal-close").focus();
}
function closeModal() {
  if (modal.hidden) return;
  modal.hidden = true;
  document.body.style.overflow = "";
  if (lastFocused && lastFocused.focus) lastFocused.focus();
}

cardsEl.addEventListener("click", e => {
  const c = e.target.closest(".card");
  if (c) openModal(+c.dataset.i);
});
cardsEl.addEventListener("keydown", e => {
  if (e.key !== "Enter" && e.key !== " ") return;
  const c = e.target.closest(".card");
  if (c) { e.preventDefault(); openModal(+c.dataset.i); }
});
modal.querySelector(".modal-backdrop").addEventListener("click", closeModal);
modal.querySelector(".modal-close").addEventListener("click", closeModal);
document.addEventListener("keydown", e => { if (e.key === "Escape") closeModal(); });

chips.forEach(ch => ch.addEventListener("click", () => {
  chips.forEach(c => { c.classList.remove("active"); c.setAttribute("aria-pressed", "false"); });
  ch.classList.add("active");
  ch.setAttribute("aria-pressed", "true");
  activeFilter = ch.dataset.filter;
  render();
}));
searchEl.addEventListener("input", () => { query = searchEl.value; render(); });


